from typing import Protocol

from app.domain.entities.product import Product
from app.domain.entities.shopping_list import ShoppingList


class ShoppingListRepository(Protocol):
    """Porta de persistência consumida pelos serviços de aplicação."""
    def create(self, shopping_list: ShoppingList) -> ShoppingList: ...
    def get_by_id(self, list_id: int) -> ShoppingList | None: ...
    def get_all(self) -> list[ShoppingList]: ...
    def delete(self, list_id: int) -> bool: ...


class ProductRepository(Protocol):
    """Porta de persistência de produtos; a implementação pode variar."""
    def create(self, list_id: int, product: Product) -> Product: ...
    def get_by_list_id(self, list_id: int) -> list[Product]: ...
    def delete(self, product_id: int, list_id: int | None = None) -> bool: ...
